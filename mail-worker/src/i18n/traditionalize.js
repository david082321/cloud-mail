function traditionalizeText(value) {
    let result = value

    for (const [source, target] of phraseReplacements) {
        result = result.replaceAll(source, target)
    }

    return [...result].map(character => characterReplacements[character] || character).join('')
}

export function traditionalizeLocale(locale) {
    if (typeof locale === 'string') return traditionalizeText(locale)
    if (Array.isArray(locale)) return locale.map(traditionalizeLocale)
    if (locale && typeof locale === 'object') {
        return Object.fromEntries(Object.entries(locale).map(([key, value]) => [key, traditionalizeLocale(value)]))
    }
    return locale
}
